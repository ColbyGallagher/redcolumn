export type Rgb = [number, number, number];

/** RGB (0-1) of an ACI index; out-of-range indexes are black. */
export function aciRgb(index: number): Rgb {
  const i = Math.abs(Math.round(index));
  if (i < 1 || i > 255) return [0, 0, 0];
  const v = parseInt(PALETTE.slice(i * 6, i * 6 + 6), 16);
  return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255];
}

/** RGB (0-1) of a DXF true colour (group 420: 0x00RRGGBB). */
export function trueRgb(v: number): Rgb {
  return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255];
}

import type { ColumnSet, Viewport } from '@nb/markup';
import type { Scale } from '@nb/measure';
import type {
  Actor as OpsActor,
  AnyOperation,
  Negotiation,
  Operation,
  OpsState,
  ProtocolRange,
  Rejection,
} from '@nb/ops';
import type { SheetInfo } from '@nb/sheets';

/** Connection lifecycle reported by a synced document. */
export type ConnectionState =
  | 'disconnected'
  | 'connecting'
  | 'connected'
  | 'reconnecting'
  | 'update_required'
  | 'revoked';

/**
 * Why a pending operation (or batch) was rejected by the server or dropped during local rebase.
 * Extends `@nb/ops` reducer rejections with transport/server outcomes.
 */
export type ServerRejection =
  | Rejection
  | { code: 'forbidden'; message?: string }
  | { code: 'op_id_reused'; opId: string }
  | { code: 'dependency_rejected'; dependsOnOpId: string }
  | { code: 'batch_rejected'; batchId: string; failedOpId: string };

/** One rejected local change held in the inbox so the user can copy, retry as new, or discard it. */
export interface InboxEntry {
  /** Stable id for this inbox entry (the op's `opId`, or `batchId` for a rejected batch). */
  readonly id: string;
  /** The rejected operation(s), in their original order. */
  readonly ops: readonly Operation[];
  /** Why it was refused. */
  readonly reason: ServerRejection;
  /** Client clock timestamp when it entered the inbox. */
  readonly rejectedAt: number;
  /** Short human-readable summary of the change. */
  readonly label: string;
}

/** Sync state and inbox controls exposed by `SyncDocument`. */
export interface SyncStatus {
  /** Number of local operations still waiting for server acknowledgement. */
  readonly pendingCount: number;
  /** Rejected operations kept for inspection, retry, or discard (stable array until changed). */
  readonly inbox: readonly InboxEntry[];
  /** Current connection state. */
  readonly connection: ConnectionState;
  /** Opaque sync cursor from the server, or null before the first sync. */
  readonly cursor: string | null;
  /** Last transport or protocol error message, if any. */
  readonly lastError: string | null;
  /** Calls `listener` whenever sync status changes. Returns the unsubscribe function. */
  subscribe(listener: () => void): () => void;
  /** Removes an entry from the rejected inbox. */
  discardInbox(id: string): void;
  /** Returns a deep copy of the rejected operations for export or inspection. */
  copyInbox(id: string): Operation[] | undefined;
  /**
   * Re-queues a rejected entry as fresh operation(s) based on the current state's versions.
   * Returns `false` if the entry is missing or cannot be retried (e.g. its target was deleted).
   */
  retryInboxAsNew(id: string): boolean;
  /** Sends any queued pending operations if connected. */
  flush(): Promise<void>;
}

/** Optional facet implemented by synced documents. */
export interface SyncFacet {
  readonly sync: SyncStatus;
}

/** The records an undo step can change. An issue only ever has its tick undone. */
export type UndoKind = 'markup' | 'placement' | 'issue';

/** Version expectation recorded with an undo/redo step so concurrent edits to the same group block undo. */
export interface UndoGroupCheck {
  kind: UndoKind;
  entityId: string;
  /**
   * Field-group key (e.g. `'text'`, `'style'`, `'fields.cost'`, `'geometry'`, `'deleted'`), or `'*'`
   * for a newly created record (meaning no group may have been modified by an un-reverted change).
   */
  group: string;
  /** The opId that produced this group's state. */
  expectedOpId: string;
  /** The opId that held this group before the step ran, used to chain consecutive undos cleanly. */
  preOpId: string | null;
  /** For `group: '*'`: own undo/redo opIds that returned edited groups back to the created state. */
  revertedOpIds?: string[];
}

/** Template for one inverse (or forward redo) operation generated by an undo/redo step. */
export interface UndoOpSpec {
  type:
    | 'markup.patch'
    | 'markup.delete'
    | 'markup.restore'
    | 'placement.patch'
    | 'placement.delete'
    | 'placement.restore'
    | 'placement.create'
    | 'issue.patch';
  entityId: string;
  payload: Record<string, unknown>;
  /** Group keys whose `basedOn` values are attached when the inverse operation is emitted. */
  groups: string[];
}

/** A group touched by an undo step's `forward` ops; becomes a check on the step pushed after it runs. */
export interface ForwardCheck {
  kind: UndoKind;
  entityId: string;
  group: string;
  /**
   * Set when the original step created the record (a `'*'` check). The reverse step then checks
   * `'*'` again, so undoing a re-done add still refuses if anyone else edited the record.
   */
  created?: { expectedOpId: string; revertedOpIds: string[] };
}

/** One entry on the client's local undo or redo stack. Plain JSON so it persists across restarts. */
export interface UndoStep {
  id: string;
  label: string;
  at: number;
  /** Every check that must pass before any operation of this step is sent (all or nothing). */
  checks: UndoGroupCheck[];
  /** Operations emitted to undo this step, in application order. */
  inverse: UndoOpSpec[];
  /** Operations emitted to redo this step after it is undone, in application order. */
  forward: UndoOpSpec[];
  /** Group keys touched by `forward`, used to build the matching redo step's checks. */
  forwardChecks: ForwardCheck[];
  /** OpIds originally emitted by this step (used to drop the step if those ops are rejected). */
  sourceOpIds: string[];
  /**
   * Stands for a change that is never undone (a status change). It has no checks or operations:
   * undoing it only takes it off the stack and reports `permanent`.
   */
  permanent?: boolean;
}

/** Persisted document setup (scales, viewports, sheets, columns). */
export interface PersistedSetup {
  scales: Record<number, Scale>;
  viewports: Viewport[];
  sheets: Record<number, SheetInfo>;
  columnSet: ColumnSet | null;
}

/** Durable local state stored per document key by a {@link SyncPersistence} adapter. */
export interface PersistedSyncState {
  formatVersion: 1;
  confirmed: OpsState;
  cursor: string | null;
  pending: Operation[];
  inbox: InboxEntry[];
  undoStack: UndoStep[];
  redoStack: UndoStep[];
  confirmedOpIds: string[];
  setup?: PersistedSetup;
  /** True once the server revoked access: the document reopens read-only with no cached content. */
  revoked?: boolean;
  /**
   * Undo/redo requests whose ops already left the client but are not confirmed yet. Their ops stay
   * in `pending` (resent with the same opIds) and the step completes once the server confirms them.
   */
  history?: PersistedHistoryRequest[];
}

/** An undo/redo request that was sent but not yet confirmed, kept across disconnects and restarts. */
export interface PersistedHistoryRequest {
  kind: 'undo' | 'redo';
  stepId: string;
  emittedOps: Operation[];
}

/** One committed event (single op or atomic batch) delivered by the server in stream order. */
export interface ServerEvent {
  ops: readonly AnyOperation[];
  seq: number;
  cursor: string;
  serverTime: number;
  actor: OpsActor;
  laneId: string;
}

/** Handshake parameters passed to a transport when connecting. */
export interface SyncHandshake {
  streamId: string;
  cursor: string | null;
  protocol: ProtocolRange;
  /** Operations still waiting for an answer, so a snapshot can say which were already applied. */
  pendingOpIds?: readonly string[];
}

/** Messages a server delivers to a connected client over a {@link SyncTransport}. */
export type ServerMessage =
  | {
      type: 'welcome';
      protocol: Negotiation;
      snapshot?: { state: OpsState; cursor: string; appliedOpIds?: readonly string[] };
      events?: readonly ServerEvent[];
    }
  | {
      type: 'ack';
      opIds: readonly string[];
      seq: number;
      cursor: string;
      serverTime: number;
      actor: OpsActor;
      laneId: string;
    }
  | {
      type: 'reject';
      opIds: readonly string[];
      failedOpId: string;
      reason: ServerRejection;
    }
  | {
      type: 'event';
      event: ServerEvent;
    }
  | {
      type: 'snapshot';
      state: OpsState;
      cursor: string;
      appliedOpIds?: readonly string[];
    }
  | {
      type: 'revoked';
      reason?: string;
    };

/** Low-level connection state exposed by a {@link SyncTransport}. */
export type TransportState = 'disconnected' | 'connecting' | 'connected';

/**
 * Transport seam between `SyncDocument` and a server (in-process for tests, WebSocket later).
 * Implementations deliver server messages in stream order and send single ops or atomic batches.
 */
export interface SyncTransport {
  readonly state: TransportState;
  connect(handshake: SyncHandshake): void | Promise<void>;
  disconnect(): void | Promise<void>;
  /** Sends a single operation or an atomic batch (all sharing one `batchId` and `batchSize`). */
  send(ops: readonly Operation[]): void | Promise<void>;
  onMessage(listener: (message: ServerMessage) => void): () => void;
  onStateChange(listener: (state: TransportState) => void): () => void;
}

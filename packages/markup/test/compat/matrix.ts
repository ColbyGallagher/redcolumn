// Turns the counts from run.ts into the compatibility matrix (docs/compatibility.md). Each status is
// worked out here from the counts, never typed in by hand. The rules are written into the doc.

/** What one fixture set found for one feature in one column. */
export interface Cell {
  /** Items the fixtures contained for this feature and column. */
  items: number;
  /** How many of `items` came from Revu-produced fixtures. */
  revuItems: number;
  /** Items that did not come through whole, named; the first few are kept for the doc. */
  failed: string[];
  failedCount: number;
  /** Things that came out that were not in the source (for example, a markup written twice). */
  extra: string[];
  extraCount: number;
  /** False for a column that has no writer yet: every item is then not yet written. */
  writer?: boolean;
  /** Set when a fixture for this cell threw; the cell then shows Error. */
  error?: string;
}

/** A table: feature rows against format columns. `notRun` says why a column could not run at all. */
export interface Table {
  rows: string[];
  columns: string[];
  cells: Record<string, Record<string, Cell>>;
  notRun: Record<string, string>;
}

export interface FixtureRecord {
  id: string;
  format: string;
  source: 'revu' | 'synthetic';
  file: string;
  status: 'ok' | 'missing' | 'error';
  items: number;
  reason?: string;
}

export interface Results {
  annotations: Table;
  exchange: Table;
  fixtures: FixtureRecord[];
  /** Fixtures the run could not read at all, or that were skipped for a reason (for example, no Revu settings folder). */
  skipped: string[];
}

export type Status = 'Supported' | 'Partial' | 'Not yet' | 'Not run' | 'Error' | '—';

/** The status of one cell, from its counts. Not run and — are the only ones with no items. */
export function statusOf(cell: Cell | undefined, notRun: string | undefined): { status: Status; detail: string } {
  if (cell?.error) return { status: 'Error', detail: cell.error };
  if (!cell || cell.items === 0) return notRun ? { status: 'Not run', detail: notRun } : { status: '—', detail: '' };
  if (cell.writer === false) return { status: 'Not yet', detail: `0/${cell.items} (no writer yet)` };
  const passed = Math.max(0, cell.items - cell.failedCount);
  const detail = `${passed}/${cell.items}${cell.extraCount ? ` (+${cell.extraCount} extra)` : ''}`;
  if (cell.failedCount === 0 && cell.extraCount === 0) return { status: cell.revuItems > 0 ? 'Supported' : 'Partial', detail };
  if (cell.failedCount >= cell.items) return { status: 'Not yet', detail };
  return { status: 'Partial', detail };
}

const cellText = (cell: Cell | undefined, notRun: string | undefined) => {
  const { status, detail } = statusOf(cell, notRun);
  return detail && status !== '—' ? `**${status}** ${detail}` : status;
};

/** Pipes and line breaks would break a Markdown table cell. */
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ');

function table(t: Table): string[] {
  const head = ['Feature', ...t.columns.map((c) => esc(c))];
  const out = [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`];
  for (const row of t.rows) {
    const cells = t.columns.map((c) => cellText(t.cells[row]?.[c], t.notRun[`${row}|${c}`] ?? t.notRun[c]));
    out.push(`| ${esc(row)} | ${cells.join(' | ')} |`);
  }
  return out;
}

function failures(t: Table): string[] {
  const out: string[] = [];
  for (const row of t.rows)
    for (const col of t.columns) {
      const cell = t.cells[row]?.[col];
      if (!cell || (!cell.failedCount && !cell.extraCount && !cell.error)) continue;
      out.push(`### ${row} · ${col}`, '');
      if (cell.error) out.push(`- Error: ${cell.error}`);
      for (const f of cell.failed) out.push(`- missing: ${f}`);
      if (cell.failedCount > cell.failed.length) out.push(`- …and ${cell.failedCount - cell.failed.length} more missing`);
      for (const f of cell.extra) out.push(`- extra: ${f}`);
      if (cell.extraCount > cell.extra.length) out.push(`- …and ${cell.extraCount - cell.extra.length} more extra`);
      out.push('');
    }
  return out;
}

/** The matrix document, as Markdown. Deterministic: the same results always give the same text. */
export function renderMatrix(r: Results): string {
  const lines: string[] = [
    '# Bluebeam compatibility matrix',
    '',
    'Generated by `packages/markup/test/compat/run.ts` from `compat-results.json`. Do not edit by hand; run `pnpm --filter @nb/markup compat` to regenerate.',
    '',
    'Counts are items that came through whole, over the items in the fixtures. Items are annotations for PDF and BAX, markups for XFDF, and tools, line styles, hatches and columns for the settings files.',
    '',
    '## Status',
    '',
    '- **Supported**: every item in the fixtures came through, and at least one Revu-produced fixture covers it.',
    '- **Partial**: some items came through, or every item passed but only synthetic fixtures cover it.',
    '- **Not yet**: nothing came through, or the format has no writer yet.',
    '- **Not run**: the fixtures were missing, or the run had no settings folder. The reason is shown.',
    '- **Error**: a fixture threw. This is a failure, not a skip.',
    '- **—**: the fixtures contain no items of this kind.',
    '',
    'A cell is never rounded to a percentage. An item that is neither mapped nor kept is a failure and is named below.',
    '',
    '## Markup in PDFs, BAX and XFDF',
    '',
    ...table(r.annotations),
    '',
    '## Settings and exchange files',
    '',
    ...table(r.exchange),
    '',
    '## Fixtures',
    '',
    '| Id | Format | Source | File | Status | Items |',
    '| --- | --- | --- | --- | --- | --- |',
    ...r.fixtures.map((f) => `| ${esc(f.id)} | ${f.format} | ${f.source} | ${esc(f.file)} | ${f.status}${f.reason ? `: ${esc(f.reason)}` : ''} | ${f.items} |`),
    '',
  ];
  if (r.skipped.length) lines.push('## Not run', '', ...r.skipped.map((s) => `- ${s}`), '');
  const fails = [...failures(r.annotations), ...failures(r.exchange)];
  if (fails.length) lines.push('## Items that did not come through', '', ...fails);
  lines.push(
    '## Known limits',
    '',
    '- BAX leaves out links and form fields, as Revu does. Pop-ups are nested inside their markup and are counted.',
    '- The BAX column checks our export against the PDF it came from. A Revu BAX is only a reference when it was exported from that same PDF; a mismatch is listed under Not run.',
    '- PDF and BAX rows count annotations; XFDF rows count markups. One markup can be several annotations (a count group, or a markup with replies and states), so the two counts differ.',
    '- Settings files are read only. No writer exists for .btx, .blx, .bhx or .bpx yet, so their Write cells are Not yet.',
    '- A fixture only proves what it contains. Add Revu-produced files for each feature before a cell can read Supported.',
    '',
  );
  return lines.join('\n');
}
